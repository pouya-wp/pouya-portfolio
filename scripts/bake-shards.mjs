import { build } from 'esbuild';
import { existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const threeRoot = path.resolve(existsSync('node_modules/three/package.json') ? 'node_modules/three' : 'work/three-package/package');
mkdirSync('work', { recursive: true });

const entry = [
  "import { readFileSync, writeFileSync } from 'node:fs';",
  "import * as THREE from 'three';",
  "import { parseGlb, normaliseMesh, shardSeeds, fractureShell, seamRibbons, surfacePoints, meshToGeometry } from './app/sculpture-model';",
  "import { SCULPTURE } from './app/story';",
  "const file = readFileSync('public/sculpture.glb');",
  "const raw = file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength);",
  "console.log('Generating pre-baked sculpture geometry...');",
  "const start = performance.now();",
  "const mesh = normaliseMesh(parseGlb(raw), SCULPTURE.height);",
  "let seed = 41;",
  "const random = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };",
  "const seeds = shardSeeds(mesh, SCULPTURE.shards, random);",
  "const shards = fractureShell(mesh, seeds, SCULPTURE.thickness);",
  "const seams = seamRibbons(shards);",
  "const points = surfacePoints(mesh, 11000, random);",
  "const whole = meshToGeometry(mesh);",
  "",
  "// Calculate buffer size",
  "let totalBytes = 0;",
  "// 1. points (11000 * 3 * 4)",
  "totalBytes += 4 + points.byteLength;",
  "// 2. whole (position + normal + index)",
  "const wholePos = whole.getAttribute('position').array;",
  "const wholeNorm = whole.getAttribute('normal').array;",
  "const wholeIdx = whole.getIndex().array;",
  "totalBytes += 4 + wholePos.byteLength + 4 + wholeNorm.byteLength + 4 + wholeIdx.byteLength;",
  "// 3. seams (position + normal + aAcross + aSide)",
  "const seamPos = seams.getAttribute('position').array;",
  "const seamNorm = seams.getAttribute('normal').array;",
  "const seamAcross = seams.getAttribute('aAcross').array;",
  "const seamSide = seams.getAttribute('aSide').array;",
  "totalBytes += 4 + seamPos.byteLength + 4 + seamNorm.byteLength + 4 + seamAcross.byteLength + 4 + seamSide.byteLength;",
  "// 4. shards",
  "totalBytes += 4; // shards count",
  "for (const s of shards) {",
  "  totalBytes += 12; // centre (3 floats)",
  "  totalBytes += 4; // groups count",
  "  totalBytes += s.geometry.groups.length * 12; // start, count, matIndex",
  "  const pos = s.geometry.getAttribute('position').array;",
  "  const norm = s.geometry.getAttribute('normal').array;",
  "  totalBytes += 4 + pos.byteLength + 4 + norm.byteLength;",
  "}",
  "",
  "const buffer = new ArrayBuffer(totalBytes);",
  "const view = new DataView(buffer);",
  "let offset = 0;",
  "",
  "// Helper writers",
  "const writeF32Array = arr => {",
  "  view.setUint32(offset, arr.length, true); offset += 4;",
  "  new Float32Array(buffer, offset, arr.length).set(arr);",
  "  offset += arr.byteLength;",
  "};",
  "const writeU32Array = arr => {",
  "  view.setUint32(offset, arr.length, true); offset += 4;",
  "  new Uint32Array(buffer, offset, arr.length).set(arr);",
  "  offset += arr.byteLength;",
  "};",
  "",
  "// 1. points",
  "writeF32Array(points);",
  "",
  "// 2. whole",
  "writeF32Array(wholePos);",
  "writeF32Array(wholeNorm);",
  "writeU32Array(wholeIdx);",
  "",
  "// 3. seams",
  "writeF32Array(seamPos);",
  "writeF32Array(seamNorm);",
  "writeF32Array(seamAcross);",
  "writeF32Array(seamSide);",
  "",
  "// 4. shards",
  "view.setUint32(offset, shards.length, true); offset += 4;",
  "for (const s of shards) {",
  "  view.setFloat32(offset, s.centre.x, true); offset += 4;",
  "  view.setFloat32(offset, s.centre.y, true); offset += 4;",
  "  view.setFloat32(offset, s.centre.z, true); offset += 4;",
  "  view.setUint32(offset, s.geometry.groups.length, true); offset += 4;",
  "  for (const g of s.geometry.groups) {",
  "    view.setUint32(offset, g.start, true); offset += 4;",
  "    view.setUint32(offset, g.count, true); offset += 4;",
  "    view.setUint32(offset, g.materialIndex, true); offset += 4;",
  "  }",
  "  const pos = s.geometry.getAttribute('position').array;",
  "  const norm = s.geometry.getAttribute('normal').array;",
  "  writeF32Array(pos);",
  "  writeF32Array(norm);",
  "}",
  "",
  "writeFileSync('public/shards-baked.bin', Buffer.from(buffer));",
  "console.log('Successfully baked sculpture geometry in ' + (performance.now() - start).toFixed(1) + 'ms -> public/shards-baked.bin (' + totalBytes + ' bytes)');",
].join('\n');

await build({
  stdin: { contents: entry, resolveDir: process.cwd(), loader: 'ts' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile: 'work/bake-shards-runner.mjs',
  plugins: [{
    name: 'three-local',
    setup(builder) {
      builder.onResolve({ filter: /^three($|\/)/ }, args => ({
        path: args.path === 'three'
          ? path.join(threeRoot, 'build/three.module.js')
          : path.join(threeRoot, args.path.replace('three/addons/', 'examples/jsm/').replace(/^three\//, '')),
      }));
    },
  }],
});

await import(pathToFileURL(path.resolve('work/bake-shards-runner.mjs')).href);
